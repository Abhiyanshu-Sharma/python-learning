def happyBirthday():
    print("Happy Birthday to you!")
    print("You are old")
    print("Happy Birthday to you!")
    print()

def happyBirthday1(name):
    print(f"Happy Birthday to {name}!")
    print("You are old")
    print("Happy Birthday to you!")
    print()

def happyBirthday2(name, age):
    print(f"Happy Birthday to {name}!")
    print(f"You are {age} years old")
    print("Happy Birthday to you!")
    print()

happyBirthday()
happyBirthday1("Abhiyanshu")
happyBirthday2("Abhi", 21)